DROP SCHEMA IF EXISTS gestfast CASCADE;
CREATE SCHEMA gestfast;
SET search_path TO gestfast;

-- Busca sem diferenciar maiúsculas nem acentos, como o MySQL fazia ("pao" acha "Pão").
CREATE FUNCTION sem_acento(t TEXT) RETURNS TEXT LANGUAGE SQL IMMUTABLE AS $$
  SELECT lower(translate(t, 'áàãâäéèêëíìîïóòõôöúùûüçñÁÀÃÂÄÉÈÊËÍÌÎÏÓÒÕÔÖÚÙÛÜÇÑ', 'aaaaaeeeeiiiiooooouuuucnaaaaaeeeeiiiiooooouuuucn'))
$$;

-- ---------------------------------------------------------------------
-- Usuários, perfis e acesso
-- ---------------------------------------------------------------------
CREATE TABLE perfil (
  id_perfil   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_perfil VARCHAR(30) NOT NULL UNIQUE            -- Administrador, BackOffice, Funcionario
);

CREATE TABLE usuario (
  id_usuario   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome         VARCHAR(150) NOT NULL,
  email        VARCHAR(150) NOT NULL UNIQUE,          -- login
  senha        VARCHAR(255) NOT NULL,                 -- hash scrypt (nunca texto puro)
  cargo        VARCHAR(100),
  status       VARCHAR(40) CHECK (status IN ('Ativo','Inativo')) NOT NULL DEFAULT 'Ativo',
  data_criacao DATE NOT NULL,
  id_perfil    INT NOT NULL,
  FOREIGN KEY (id_perfil) REFERENCES perfil(id_perfil)
);

-- Sessões de login (guarda só o hash do token do cookie)
CREATE TABLE sessao (
  hash       CHAR(64) PRIMARY KEY,
  id_usuario INT NOT NULL,
  lembrar    BOOLEAN NOT NULL DEFAULT FALSE,
  criado     BIGINT NOT NULL,                         -- milissegundos (Date.now())
  expira     BIGINT NOT NULL,
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario) ON DELETE CASCADE
);
CREATE INDEX idx_sessao_usuario ON sessao(id_usuario);

-- Links de redefinição de senha (uso único, 30 minutos)
CREATE TABLE token_reset (
  hash       CHAR(64) PRIMARY KEY,
  id_usuario INT NOT NULL,
  expira     BIGINT NOT NULL,
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario) ON DELETE CASCADE
);

-- Parâmetros do sistema (linha única, id = 1)
CREATE TABLE configuracao (
  id                              SMALLINT PRIMARY KEY DEFAULT 1,
  estabelecimento                 VARCHAR(150) NOT NULL,
  desconto_maximo_percent         DECIMAL(5,2) NOT NULL DEFAULT 20,
  intervalo_atualizacao_seg       INT NOT NULL DEFAULT 3,
  simular_cartao_negado           BOOLEAN NOT NULL DEFAULT FALSE,
  simular_fornecedor_indisponivel BOOLEAN NOT NULL DEFAULT FALSE,
  dias_alerta_validade            INT NOT NULL DEFAULT 3,  -- avisa quando faltam N dias (ou menos) para vencer
  exigir_caixa_aberto             BOOLEAN NOT NULL DEFAULT TRUE,
  balanca_modo                    VARCHAR(40) CHECK (balanca_modo IN ('peso','preco')) NOT NULL DEFAULT 'peso',
  balanca_digitos_codigo          SMALLINT NOT NULL DEFAULT 5,
  CHECK (id = 1)
);

-- ---------------------------------------------------------------------
-- Catálogo
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
  id_categoria   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_categoria VARCHAR(100) NOT NULL UNIQUE,
  descricao      VARCHAR(255)
);

CREATE TABLE fornecedor (
  id_fornecedor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          VARCHAR(150) NOT NULL UNIQUE,
  whatsapp      VARCHAR(15) NULL                      -- só dígitos, com DDI 55 (botão "Enviar pelo WhatsApp")
);

CREATE TABLE produto (
  id_produto         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_barras      VARCHAR(100) NOT NULL UNIQUE,
  codigo_balanca     INT NULL,                          -- código do produto na etiqueta da balança
  nome_produto       VARCHAR(200) NOT NULL,
  descricao          TEXT,
  unidade            VARCHAR(20) NOT NULL DEFAULT 'UN', -- KG e Lt aceitam fração; as demais só inteiros
  peso               VARCHAR(30),
  preco_custo        DECIMAL(10,2) NOT NULL DEFAULT 0,
  preco_venda        DECIMAL(10,2) NOT NULL,
  preco_min          DECIMAL(10,2) NOT NULL,
  preco_max          DECIMAL(10,2) NOT NULL,
  quantidade_estoque DECIMAL(12,3) NOT NULL DEFAULT 0,
  estoque_minimo     DECIMAL(12,3) NOT NULL DEFAULT 0,
  lote               VARCHAR(40),
  validade           DATE,
  imagem             VARCHAR(255),
  status             VARCHAR(40) CHECK (status IN ('Ativo','Inativo')) NOT NULL DEFAULT 'Ativo',
  tipo               VARCHAR(40) CHECK (tipo IN ('Revenda','Produção','Insumo')) NOT NULL DEFAULT 'Revenda', -- Insumo não é vendido no caixa
  unidade_compra     VARCHAR(20),                       -- ex.: 'Saco' (compra) com estoque em KG
  fator_conversao    DECIMAL(12,3) NOT NULL DEFAULT 1,  -- quantas unidades de estoque vêm em 1 unidade de compra
  id_categoria       INT NOT NULL,
  FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria),
  CHECK (preco_venda > 0),
  CHECK (preco_min <= preco_venda AND preco_venda <= preco_max),
  CHECK (quantidade_estoque >= 0),
  CONSTRAINT uq_produto_balanca UNIQUE (codigo_balanca),
  CHECK (fator_conversao > 0)
);

CREATE TABLE alerta_estoque (
  id_alerta     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_alerta   TIMESTAMP(0) NOT NULL,
  mensagem      VARCHAR(255) NOT NULL,
  status_alerta VARCHAR(40) CHECK (status_alerta IN ('Ativo','Resolvido')) NOT NULL DEFAULT 'Ativo',
  id_produto    INT NOT NULL,
  FOREIGN KEY (id_produto) REFERENCES produto(id_produto)
);

-- ---------------------------------------------------------------------
-- Compras (requisições a fornecedores)
-- ---------------------------------------------------------------------
CREATE TABLE requisicao (
  id_requisicao              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_pedido              VARCHAR(20) NOT NULL UNIQUE,
  pedido_grupo               VARCHAR(20) NULL,        -- pedido em massa: requisições feitas juntas (PED-9661)
  id_fornecedor              INT NOT NULL,
  id_produto                 INT NULL,                -- pode ser item ainda não cadastrado
  produto_nome               VARCHAR(200) NOT NULL,
  quantidade_pedida          DECIMAL(12,3) NOT NULL,
  quantidade_atendida        DECIMAL(12,3) NOT NULL DEFAULT 0,
  unidade                    VARCHAR(20) NOT NULL,
  valor_unitario             DECIMAL(10,2) NOT NULL,
  valor_total                DECIMAL(12,2) NOT NULL,
  situacao                   VARCHAR(40) CHECK (situacao IN ('Em Aberto','Cotado','AF Gerada','Finalizado','Cancelado')) NOT NULL DEFAULT 'Em Aberto',
  data_pedido                DATE NOT NULL,
  previsao_entrega           DATE,
  endereco_entrega           VARCHAR(255),
  observacao                 TEXT,
  justificativa_cancelamento TEXT,
  FOREIGN KEY (id_fornecedor) REFERENCES fornecedor(id_fornecedor),
  FOREIGN KEY (id_produto) REFERENCES produto(id_produto),
  CHECK (quantidade_pedida > 0)
);

CREATE TABLE requisicao_historico (
  id_historico  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_requisicao INT NOT NULL,
  data_registro TIMESTAMP(0) NOT NULL,
  situacao      VARCHAR(60) NOT NULL,                 -- inclui "Recebimento parcial (4 Pacote)"
  id_usuario    INT,
  FOREIGN KEY (id_requisicao) REFERENCES requisicao(id_requisicao) ON DELETE CASCADE,
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario)
);

-- Pedidos predefinidos (ex.: "Pedido semanal do moinho"): fornecedor + itens com a quantidade de sempre.
CREATE TABLE pedido_modelo (
  id_modelo     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          VARCHAR(80) NOT NULL UNIQUE,
  id_fornecedor INT NOT NULL,
  observacao    TEXT,
  atualizado_em TIMESTAMP(0) NOT NULL,
  id_usuario    INT,
  FOREIGN KEY (id_fornecedor) REFERENCES fornecedor(id_fornecedor),
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario)
);

CREATE TABLE item_pedido_modelo (
  id_modelo  INT NOT NULL,
  id_produto INT NOT NULL,
  quantidade DECIMAL(12,3) NOT NULL,
  PRIMARY KEY (id_modelo, id_produto),
  FOREIGN KEY (id_modelo) REFERENCES pedido_modelo(id_modelo) ON DELETE CASCADE,
  FOREIGN KEY (id_produto) REFERENCES produto(id_produto),
  CHECK (quantidade > 0)
);

-- ---------------------------------------------------------------------
-- Vendas (PDV / balcão)
-- ---------------------------------------------------------------------
-- ---------------------------------------------------------------------
-- Caixa: abertura, sangria, reforço e fechamento (a tabela venda aponta para cá)
-- ---------------------------------------------------------------------
-- Caixa único da loja: "aberto" só vale 1 enquanto está aberto, e o UNIQUE impede um segundo caixa aberto.
CREATE TABLE caixa (
  id_caixa         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status           VARCHAR(40) CHECK (status IN ('Aberto','Fechado')) NOT NULL DEFAULT 'Aberto',
  aberto           SMALLINT GENERATED ALWAYS AS (CASE WHEN status = 'Aberto' THEN 1 END) STORED,
  data_abertura    TIMESTAMP(0) NOT NULL,
  id_usuario_abertura INT NOT NULL,
  troco_inicial    DECIMAL(12,2) NOT NULL,
  data_fechamento  TIMESTAMP(0),
  id_usuario_fechamento INT,
  valor_esperado   DECIMAL(12,2),                   -- congelado no fechamento
  valor_contado    DECIMAL(12,2),
  diferenca        DECIMAL(12,2),                   -- contado - esperado
  observacao       TEXT,
  resumo           JSON,                            -- totais por forma congelados no fechamento
  CONSTRAINT uq_caixa_aberto UNIQUE (aberto),
  FOREIGN KEY (id_usuario_abertura) REFERENCES usuario(id_usuario),
  FOREIGN KEY (id_usuario_fechamento) REFERENCES usuario(id_usuario),
  CHECK (troco_inicial >= 0)
);
CREATE INDEX idx_caixa_abertura ON caixa(data_abertura);

CREATE TABLE venda (
  id_venda            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_venda        VARCHAR(20) NOT NULL UNIQUE,
  data_venda          TIMESTAMP(0) NOT NULL,
  valor_subtotal      DECIMAL(12,2) NOT NULL,
  desconto            DECIMAL(12,2) NOT NULL DEFAULT 0,
  desconto_tipo       VARCHAR(40) CHECK (desconto_tipo IN ('valor','percentual')) NOT NULL DEFAULT 'valor',
  desconto_informado  DECIMAL(12,2) NOT NULL DEFAULT 0, -- valor digitado (R$ ou %), usado ao editar a venda
  valor_total         DECIMAL(12,2) NOT NULL,
  forma_pagamento     VARCHAR(40) CHECK (forma_pagamento IN ('Dinheiro','Cartão Débito','Cartão Crédito','PIX','Misto')) NOT NULL, -- Misto: partes em venda_pagamento
  valor_recebido      DECIMAL(12,2),
  troco               DECIMAL(12,2),
  nsu                 VARCHAR(20),
  status_venda        VARCHAR(40) CHECK (status_venda IN ('Concluída','Cancelada')) NOT NULL DEFAULT 'Concluída',
  motivo_cancelamento TEXT,
  data_cancelamento   TIMESTAMP(0),
  cancelada_por       INT,
  autorizada_por      INT,
  editada_por         INT,
  data_edicao         TIMESTAMP(0),
  id_usuario          INT NOT NULL,
  id_caixa            INT NULL,                        -- NULL: venda sem controle de caixa
  CONSTRAINT fk_venda_caixa FOREIGN KEY (id_caixa) REFERENCES caixa(id_caixa),
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
  FOREIGN KEY (cancelada_por) REFERENCES usuario(id_usuario),
  FOREIGN KEY (autorizada_por) REFERENCES usuario(id_usuario),
  FOREIGN KEY (editada_por) REFERENCES usuario(id_usuario)
);
CREATE INDEX idx_venda_caixa ON venda(id_caixa);

CREATE TABLE item_venda (
  id_item_venda  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venda       INT NOT NULL,
  id_produto     INT NOT NULL,
  quantidade     DECIMAL(12,3) NOT NULL CHECK (quantidade > 0),
  valor_unitario DECIMAL(10,2) NOT NULL,              -- preço praticado no momento da venda
  subtotal       DECIMAL(12,2) NOT NULL,
  FOREIGN KEY (id_venda) REFERENCES venda(id_venda) ON DELETE CASCADE,
  FOREIGN KEY (id_produto) REFERENCES produto(id_produto)
);

-- Partes de uma venda com pagamento misto (ex.: R$ 20 no PIX + R$ 15 em dinheiro).
CREATE TABLE venda_pagamento (
  id_venda_pagamento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venda           INT NOT NULL,
  forma_pagamento    VARCHAR(40) CHECK (forma_pagamento IN ('Dinheiro','Cartão Débito','Cartão Crédito','PIX')) NOT NULL,
  valor              DECIMAL(12,2) NOT NULL,
  nsu                VARCHAR(20),
  FOREIGN KEY (id_venda) REFERENCES venda(id_venda) ON DELETE CASCADE,
  CHECK (valor > 0)
);

CREATE TABLE caixa_movimento (
  id_movimento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_caixa     INT NOT NULL,
  tipo         VARCHAR(40) CHECK (tipo IN ('sangria','reforco','estorno')) NOT NULL,
  valor        DECIMAL(12,2) NOT NULL,
  motivo       VARCHAR(255) NOT NULL,
  data_movimento TIMESTAMP(0) NOT NULL,
  id_usuario   INT NOT NULL,
  id_venda     INT NULL,                            -- só no estorno de venda de um caixa já fechado
  FOREIGN KEY (id_caixa) REFERENCES caixa(id_caixa),
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
  FOREIGN KEY (id_venda) REFERENCES venda(id_venda) ON DELETE SET NULL,
  CHECK (valor > 0)
);

-- Venda em espera: segura o carrinho para atender o próximo cliente. Não reserva estoque.
CREATE TABLE venda_espera (
  id_espera     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rotulo        VARCHAR(60),
  itens         JSON NOT NULL,
  desconto      DECIMAL(12,2) NOT NULL DEFAULT 0,
  desconto_tipo VARCHAR(40) CHECK (desconto_tipo IN ('valor','percentual')) NOT NULL DEFAULT 'valor',
  criada_em     TIMESTAMP(0) NOT NULL,
  id_usuario    INT NOT NULL,
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario)
);

-- ---------------------------------------------------------------------
-- Produção: ficha técnica (receita) e registro de produção com baixa dos insumos
-- ---------------------------------------------------------------------
CREATE TABLE ficha_tecnica (
  id_ficha        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_produto      INT NOT NULL UNIQUE,              -- produto pronto (tipo Produção)
  rendimento      DECIMAL(12,3) NOT NULL,           -- quanto 1 receita rende, na unidade do produto
  nome_rendimento VARCHAR(40) NOT NULL DEFAULT 'receita', -- ex.: fornada, assadeira
  validade_dias   INT,                              -- validade do produto pronto (NULL = não altera)
  observacao      TEXT,
  atualizada_em   TIMESTAMP(0) NOT NULL,
  id_usuario      INT,
  FOREIGN KEY (id_produto) REFERENCES produto(id_produto),
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
  CHECK (rendimento > 0),
  CHECK (validade_dias IS NULL OR validade_dias >= 0)
);

CREATE TABLE item_ficha_tecnica (
  id_ficha   INT NOT NULL,
  id_insumo  INT NOT NULL,
  quantidade DECIMAL(12,3) NOT NULL,                -- por receita, na unidade do insumo
  PRIMARY KEY (id_ficha, id_insumo),
  FOREIGN KEY (id_ficha) REFERENCES ficha_tecnica(id_ficha) ON DELETE CASCADE,
  FOREIGN KEY (id_insumo) REFERENCES produto(id_produto),
  CHECK (quantidade > 0)
);

CREATE TABLE producao (
  id_producao   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_produto    INT NOT NULL,
  receitas      DECIMAL(12,3) NOT NULL,             -- quantas receitas (fornadas) foram feitas
  quantidade    DECIMAL(12,3) NOT NULL,             -- quanto entrou do produto pronto
  custo_total   DECIMAL(10,2) NOT NULL DEFAULT 0,   -- custo dos insumos consumidos
  data_producao TIMESTAMP(0) NOT NULL,
  observacao    TEXT,
  status        VARCHAR(40) CHECK (status IN ('Concluída','Estornada')) NOT NULL DEFAULT 'Concluída',
  id_usuario    INT NOT NULL,
  estornada_por INT,
  data_estorno  TIMESTAMP(0),
  motivo_estorno VARCHAR(500),
  FOREIGN KEY (id_produto) REFERENCES produto(id_produto),
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
  FOREIGN KEY (estornada_por) REFERENCES usuario(id_usuario),
  CHECK (receitas > 0 AND quantidade > 0)
);

-- ---------------------------------------------------------------------
-- Movimentações de estoque (histórico de toda entrada e saída)
-- ---------------------------------------------------------------------
CREATE TABLE movimentacao_estoque (
  id_movimentacao   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_movimentacao VARCHAR(40) CHECK (tipo_movimentacao IN ('Entrada','Saída')) NOT NULL,
  quantidade        DECIMAL(12,3) NOT NULL CHECK (quantidade > 0),
  data_movimentacao TIMESTAMP(0) NOT NULL,
  observacao        TEXT,
  origem            VARCHAR(40) CHECK (origem IN ('manual','venda','requisicao','conferencia','estorno','ajuste','perda','producao')) NOT NULL DEFAULT 'manual',
  motivo_perda      VARCHAR(40) CHECK (motivo_perda IN ('Vencido','Quebra/Avaria','Sobra do dia','Outro')),  -- só quando origem = 'perda'
  valor_unitario    DECIMAL(10,2) NOT NULL DEFAULT 0,
  id_produto        INT NOT NULL,
  id_usuario        INT,                              -- NULL = movimento do sistema
  id_producao       INT,                              -- produção que gerou o movimento (origem 'producao' e seu estorno)
  FOREIGN KEY (id_produto) REFERENCES produto(id_produto),
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario),
  FOREIGN KEY (id_producao) REFERENCES producao(id_producao)
);

-- ---------------------------------------------------------------------
-- Conferência de inventário (físico x sistema)
-- ---------------------------------------------------------------------
CREATE TABLE conferencia (
  id_conferencia   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_conferencia TIMESTAMP(0) NOT NULL,
  observacao       VARCHAR(1000),
  ajustou_estoque  BOOLEAN NOT NULL DEFAULT TRUE,
  id_usuario       INT NOT NULL,                      -- responsável pela contagem
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario)
);

CREATE TABLE item_conferencia (
  id_item_conferencia INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conferencia      INT NOT NULL,
  id_produto          INT NOT NULL,
  lote                VARCHAR(40),
  quantidade_sistema  DECIMAL(12,3) NOT NULL,
  quantidade_fisica   DECIMAL(12,3) NOT NULL,
  divergencia         DECIMAL(12,3) NOT NULL,
  FOREIGN KEY (id_conferencia) REFERENCES conferencia(id_conferencia) ON DELETE CASCADE,
  FOREIGN KEY (id_produto) REFERENCES produto(id_produto)
);

-- ---------------------------------------------------------------------
-- Relatórios gerados (auditoria)
-- ---------------------------------------------------------------------
CREATE TABLE relatorio (
  id_relatorio   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_relatorio VARCHAR(60) NOT NULL,
  data_geracao   TIMESTAMP(0) NOT NULL,
  id_usuario     INT NOT NULL,
  FOREIGN KEY (id_usuario) REFERENCES usuario(id_usuario)
);

-- ---------------------------------------------------------------------
-- Índices (cada um atende a uma consulta do db.js; ver README, seção "Banco otimizado")
